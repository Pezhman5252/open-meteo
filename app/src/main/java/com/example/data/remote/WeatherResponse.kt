package com.example.data.remote

import com.squareup.moshi.Json
import com.squareup.moshi.JsonClass

@JsonClass(generateAdapter = true)
data class WeatherUnits(
    @param:Json(name = "time") val time: String? = null,
    @param:Json(name = "interval") val interval: String? = null,
    @param:Json(name = "temperature_2m") val temperature2m: String? = "°C",
    @param:Json(name = "relative_humidity_2m") val relativeHumidity2m: String? = "%",
    @param:Json(name = "apparent_temperature") val apparentTemperature: String? = "°C",
    @param:Json(name = "precipitation") val precipitation: String? = "mm",
    @param:Json(name = "precipitation_probability") val precipitationProbability: String? = "%",
    @param:Json(name = "snowfall") val snowfall: String? = "cm",
    @param:Json(name = "snowfall_height") val snowfallHeight: String? = "m",
    @param:Json(name = "weather_code") val weatherCode: String? = "wmo",
    @param:Json(name = "wind_speed_10m") val windSpeed10m: String? = "km/h",
    @param:Json(name = "wind_direction_10m") val windDirection10m: String? = "°",
    @param:Json(name = "wind_speed_80m") val windSpeed80m: String? = "km/h",
    @param:Json(name = "wind_direction_80m") val windDirection80m: String? = "°",
    @param:Json(name = "surface_pressure") val surfacePressure: String? = "hPa",
    @param:Json(name = "pressure_msl") val pressureMsl: String? = "hPa",
    @param:Json(name = "freezing_level_height") val freezingLevelHeight: String? = "m",
    @param:Json(name = "wind_gusts_10m") val windGusts10m: String? = "km/h",
    @param:Json(name = "visibility") val visibility: String? = "m",
    @param:Json(name = "cloud_cover") val cloudCover: String? = "%",
    @param:Json(name = "dew_point_2m") val dewPoint2m: String? = "°C",
    @param:Json(name = "cape") val cape: String? = "J/kg",
    @param:Json(name = "lightning_potential") val lightningPotential: String? = "J/kg",
    @param:Json(name = "rain") val rain: String? = "mm",
    @param:Json(name = "showers") val showers: String? = "mm",
    @param:Json(name = "evapotranspiration") val evapotranspiration: String? = "mm",
    @param:Json(name = "et0_fao_evapotranspiration") val et0FaoEvapotranspiration: String? = "mm",
    @param:Json(name = "shortwave_radiation") val shortwaveRadiation: String? = "W/m²",
    @param:Json(name = "direct_radiation") val directRadiation: String? = "W/m²",
    @param:Json(name = "diffuse_radiation") val diffuseRadiation: String? = "W/m²",
    // توجه: snow_depth در استاندارد Open-Meteo بر حسب متر (m) برگردانده می‌شود، برخلاف snowfall که بر حسب سانتی‌متر (cm) است
    @param:Json(name = "snow_depth") val snowDepth: String? = "m",
    @param:Json(name = "soil_temperature_0cm") val soilTemperature0cm: String? = "°C",
    @param:Json(name = "cloud_cover_low") val cloudCoverLow: String? = "%",
    @param:Json(name = "cloud_cover_mid") val cloudCoverMid: String? = "%",
    @param:Json(name = "cloud_cover_high") val cloudCoverHigh: String? = "%",
    @param:Json(name = "uv_index_max") val uvIndexMax: String? = "index",
    @param:Json(name = "uv_index_clear_sky_max") val uvIndexClearSkyMax: String? = "index",
    @param:Json(name = "geopotential_height_500hPa") val geopotentialHeight500hPa: String? = "m",
    @param:Json(name = "geopotential_height_700hPa") val geopotentialHeight700hPa: String? = "m",
    @param:Json(name = "geopotential_height_850hPa") val geopotentialHeight850hPa: String? = "m"
)

